#!/usr/bin/env python3
"""make_index.py — generate docs/claim-evidence-index.md from the measured
aggregates and the scored findings.

Usage: make_index.py <pack_dir> <prefix>
  prefix: "" for the shipped run, "fresh-clone-" for a clean reproduction.
The index maps every measured claim to the script that produced it, the
unedited output file, and the exact numbers. It is regenerated (not
hand-edited) so the numbers in it always match the outputs.
"""
import csv
import json
import sys
from pathlib import Path

pack = Path(sys.argv[1])
prefix = sys.argv[2] if len(sys.argv) > 2 else ""
outdir = pack / "outputs"

with open(outdir / f"{prefix}bench-kem.csv") as f:
    bench = list(csv.DictReader(f))
with open(outdir / f"{prefix}hybrid-summary.csv") as f:
    hybrid = {r["label"]: r for r in csv.DictReader(f)}
with open(outdir / f"{prefix}hybrid-downgrade.csv") as f:
    downgrade = list(csv.DictReader(f))
with open(outdir / f"{prefix}rejection-summary.json") as f:
    rej = json.load(f)
with open(outdir / f"{prefix}findings-scored.json") as f:
    findings = json.load(f)["findings"]

bench_by = {}
for r in bench:
    bench_by.setdefault((r["scheme"], r["op"]), []).append(float(r["mean_us"]))


def bmean(scheme, op):
    ms = bench_by[(scheme, op)]
    return f"{sum(ms) / len(ms):.2f}"


def h(label, field):
    return hybrid[label][field]


tamper = [c for c in rej["cases"] if c["case"] in
          {"flip_first_bit", "flip_mid_bit", "flip_last_bit", "flip_byte",
           "all_zero_ct", "random_ct", "wrong_sk"}]
t_trials = sum(c["n"] for c in tamper)
t_rc = sum(c["rc_success"] for c in tamper)
t_eq = sum(c["ss_eq_valid"] for c in tamper)
t_det = sum(c["deterministic"] for c in tamper)

lines = []
lines.append("# Claim-to-evidence index")
lines.append("")
lines.append("Every measured claim in this assessment, the script that produced")
lines.append("it, the unedited output file, and the exact numbers. Regenerated by")
lines.append("`scripts/make_index.py` from the aggregates; the numbers below are")
lines.append("copied from the outputs, not typed by hand.")
lines.append("")
lines.append("## Sizes (FIPS 203 Table 3; RFC 7748; SEC 1)")
lines.append("")
lines.append("| Claim | Expected | Measured | Evidence |")
lines.append("|---|---|---|---|")
for scheme, fields in sorted(rej["sizes"].items()):
    for field, v in sorted(fields.items()):
        lines.append(f"| {scheme} {field} | {v['expected']} bytes | "
                     f"{v['got']} bytes ({v['status']}) | "
                     f"`outputs/{prefix}bench-kem-run1.log`, `outputs/{prefix}bench-kem-run2.log` (SIZE lines) |")
lines.append("")
lines.append("## Timings (mean of two runs, microseconds; KEM-level)")
lines.append("")
lines.append("| Operation | ML-KEM-512 | ML-KEM-768 | ML-KEM-1024 | X25519 | P-256 | P-384 |")
lines.append("|---|---|---|---|---|---|---|")
for op in ("keygen", "encaps", "decaps"):
    row = f"| {op} |"
    for scheme in ("ML-KEM-512", "ML-KEM-768", "ML-KEM-1024"):
        row += f" {bmean(scheme, op)} |"
    if op == "keygen":
        row += f" {bmean('X25519', 'keygen')} | {bmean('P-256', 'keygen')} | {bmean('P-384', 'keygen')} |"
    else:
        # X25519 / P-256 / P-384 have no encaps/decaps; they use derive.
        row += " — | — | — |"
    lines.append(row)
lines.append("| derive | — | — | — | " + bmean("X25519", "derive") + " | " + bmean("P-256", "derive") + " | " + bmean("P-384", "derive") + " |")
lines.append("")
lines.append("Source: `src/bench_kem.c`, run by `scripts/run_all.sh` as")
lines.append(f"`outputs/{prefix}bench-kem-run1.log` and `outputs/{prefix}bench-kem-run2.log`;")
lines.append(f"machine-readable form: `outputs/{prefix}bench-kem.csv`.")
lines.append("")
lines.append("## Implicit rejection (FIPS 203 section 6, Algorithm 18)")
lines.append("")
lines.append(f"- Tampered-ciphertext trials across all three parameter sets: "
             f"{t_trials} total; decapsulation returned success in {t_rc}; "
             f"shared secret equal to the valid secret in {t_eq} (zero); "
             f"deterministic implicit-rejection secret in {t_det}.")
lines.append("- Ciphertext-length check: the liboqs decaps API takes no length "
             "argument (OQS_KEM_decaps has no length parameter), so the FIPS 203 "
             "section 7.3 length check is the caller's responsibility; RFC 10024 "
             "section 4.2 requires the TLS client to perform it (finding F-05).")
lines.append(f"- Control (valid encaps/decaps): "
             f"{sum(m for ps in rej['controls'].values() for m, _ in ps)}/"
             f"{sum(t for ps in rej['controls'].values() for _, t in ps)} secret matches.")
lines.append("")
lines.append(f"Source: `src/implicit_reject.c`; logs `outputs/{prefix}rejection-run1.log`,")
lines.append(f"`outputs/{prefix}rejection-run2.log`; summary `outputs/{prefix}rejection-summary.json`.")
lines.append("")
lines.append("## Hybrid TLS 1.3 handshakes (RFC 10024)")
lines.append("")
lines.append("| Group | Mean ms | Median ms | Key share bytes | ClientHello bytes | Server CPU ms/hs | Negotiated |")
lines.append("|---|---|---|---|---|---|---|")
for label in ("X25519MLKEM768", "x25519_mlkem512", "SecP256r1MLKEM768",
              "SecP384r1MLKEM1024", "X25519", "P-256", "P-384"):
    lines.append(f"| {label} | {h(label, 'mean_ms')} | {h(label, 'median_ms')} | "
                 f"{h(label, 'key_exchange_len')} | {h(label, 'clienthello_bytes')} | "
                 f"{h(label, 'server_cpu_ms_per_handshake')} | {h(label, 'negotiated_group')} |")
lines.append("")
lines.append("Source: `scripts/run_hybrid.sh` (openssl s_server/s_client, system")
lines.append(f"OpenSSL 3.0.13, oqs-provider 0.12.0); logs `outputs/{prefix}hybrid-*.log`;")
lines.append(f"summary `outputs/{prefix}hybrid-summary.csv`.")
lines.append("")
lines.append("## Downgrade behaviour")
lines.append("")
lines.append("| Scenario | Server offers | Client offers | Expected | Actual | Verdict |")
lines.append("|---|---|---|---|---|---|")
for d in downgrade:
    lines.append(f"| {d['scenario']} | {d['server_group']} | {d['client_group']} | "
                 f"{d['expected_negotiated'] or '(handshake fails)'} | "
                 f"{d['actual_negotiated'] or '(no session)'} | {d['verdict']} |")
lines.append("")
lines.append(f"Source: `scripts/run_hybrid.sh` with separate server/client group")
lines.append(f"lists; summary `outputs/{prefix}hybrid-downgrade.csv`.")
lines.append("")
lines.append("## Findings")
lines.append("")
lines.append("| ID | Severity | Title | Evidence |")
lines.append("|---|---|---|---|")
for f in findings:
    lines.append(f"| {f['id']} | {f['severity']} ({f['score']}) | {f['title']} | "
                 f"`outputs/{prefix}findings-scored.json` |")
lines.append("")
lines.append("Full finding text, rationale, remediation, and evidence are in")
lines.append("`docs/findings-report.md` and `findings.json`.")
lines.append("")

target = pack / "docs" / "claim-evidence-index.md"
target.write_text("\n".join(lines))
print(f"make_index: wrote {target} ({len(lines)} lines)")
